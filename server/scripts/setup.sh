#!/usr/bin/env bash
# Reproducible setup of the reo-web bioserver on Ubuntu/WSL.
#
#   scripts/setup.sh          deps + db + build (asks sudo for deps/db if not root)
#   scripts/setup.sh deps     apt packages: openjdk-21-jdk-headless, mariadb-server, libmariadb-java
#   scripts/setup.sh db       create databases bioserver1/2, user, schema, test users (needs root)
#   scripts/setup.sh build    compile to build/reo-bioserver.jar (run as your normal user)
#
# From Windows (no sudo password needed with -u root):
#   wsl -u root -e bash -lc '/home/<you>/reo-web/server/scripts/setup.sh deps db'
#   wsl -e bash -lc '~/reo-web/server/scripts/setup.sh build'
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
JDBC_JAR="${JDBC_JAR:-/usr/share/java/mariadb-java-client.jar}"
LOCAL_PROPS="$ROOT/config/local.properties"
OWNER="$(stat -c %U "$ROOT")"

as_root() {
    if [ "$(id -u)" = 0 ]; then "$@"; else sudo "$@"; fi
}

do_deps() {
    echo "== deps"
    as_root env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
        openjdk-21-jdk-headless mariadb-server libmariadb-java python3 curl >/dev/null
    as_root systemctl enable --now mariadb >/dev/null 2>&1 || as_root service mariadb start
}

do_db() {
    echo "== db"
    as_root mariadb-admin ping >/dev/null 2>&1 || as_root systemctl start mariadb || as_root service mariadb start
    local pw
    if [ -f "$LOCAL_PROPS" ] && grep -q '^db.password=' "$LOCAL_PROPS"; then
        pw="$(grep '^db.password=' "$LOCAL_PROPS" | head -1 | cut -d= -f2-)"
    else
        pw="$(head -c 18 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 20)"
        {
            echo "# machine specific overrides (generated by scripts/setup.sh, not committed)"
            echo "db.password=$pw"
        } >> "$LOCAL_PROPS"
        chown "$OWNER": "$LOCAL_PROPS" 2>/dev/null || true
        chmod 600 "$LOCAL_PROPS"
    fi
    as_root mariadb <<SQL
CREATE USER IF NOT EXISTS 'bioserver'@'localhost' IDENTIFIED BY '$pw';
ALTER USER 'bioserver'@'localhost' IDENTIFIED BY '$pw';
CREATE DATABASE IF NOT EXISTS bioserver1 DEFAULT CHARACTER SET latin1 COLLATE latin1_swedish_ci;
CREATE DATABASE IF NOT EXISTS bioserver2 DEFAULT CHARACTER SET latin1 COLLATE latin1_swedish_ci;
GRANT ALL PRIVILEGES ON bioserver1.* TO 'bioserver'@'localhost';
GRANT ALL PRIVILEGES ON bioserver2.* TO 'bioserver'@'localhost';
FLUSH PRIVILEGES;
SQL
    for db in bioserver1 bioserver2; do
        as_root mariadb "$db" < "$ROOT/database/schema.sql"
        as_root mariadb "$db" < "$ROOT/database/testdata.sql"
    done
    echo "databases bioserver1/bioserver2 ready; test users test1/test1 and test2/test2"
}

do_build() {
    echo "== build"
    [ -f "$JDBC_JAR" ] || { echo "missing $JDBC_JAR (run: setup.sh deps)"; exit 1; }
    command -v javac >/dev/null || { echo "missing javac (run: setup.sh deps)"; exit 1; }
    rm -rf "$ROOT/build/classes"
    mkdir -p "$ROOT/build/classes"
    # upstream sources are latin-1 with CRLF; raw types -> silence lint
    find "$ROOT/common/src" "$ROOT/file1/src" "$ROOT/file2/src" -name '*.java' > "$ROOT/build/sources.txt"
    javac -nowarn -Xlint:none -encoding ISO-8859-1 --release 21 \
        -cp "$JDBC_JAR" -d "$ROOT/build/classes" @"$ROOT/build/sources.txt" 2>&1 | grep -v '^Note:' || true
    [ -f "$ROOT/build/classes/reo/Main.class" ] || { echo "build failed"; exit 1; }
    jar --create --file "$ROOT/build/reo-bioserver.jar" --main-class reo.Main -C "$ROOT/build/classes" .
    echo "built $ROOT/build/reo-bioserver.jar"
}

steps=("$@")
[ ${#steps[@]} -eq 0 ] && steps=(deps db build)
for s in "${steps[@]}"; do
    case "$s" in
        deps) do_deps ;;
        db) do_db ;;
        build)
            if [ "$(id -u)" = 0 ] && [ "$OWNER" != root ]; then
                # do not leave root-owned build output in the user's tree
                su "$OWNER" -c "$ROOT/scripts/setup.sh build"
            else
                do_build
            fi ;;
        *) echo "unknown step: $s"; exit 2 ;;
    esac
done
