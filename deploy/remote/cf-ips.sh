#!/usr/bin/env bash
# reo-cf-ips: refresh Cloudflare's IP ranges (https://www.cloudflare.com/ips-v4 and ips-v6).
#   - /etc/reo/cloudflare-ips.txt         the current list
#   - /etc/caddy/reo-cloudflare.caddy     "trusted_proxies static ..." (CF-Connecting-IP only from these)
#   - ufw: 80,443/tcp allowed only from these ranges (rules with comment reo-cf)
# Options: --no-firewall (do not touch ufw), --no-reload (do not reload Caddy).
# If the download fails or looks wrong, nothing changes (exit 0 with a warning; exit 1 when there is no list yet).
set -euo pipefail
LIST=/etc/reo/cloudflare-ips.txt
SNIP=/etc/caddy/reo-cloudflare.caddy
fw=1; reload=1
for a in "$@"; do
    case "$a" in
        --no-firewall) fw=0 ;;
        --no-reload) reload=0 ;;
        *) echo "usage: reo-cf-ips [--no-firewall] [--no-reload]"; exit 2 ;;
    esac
done

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
ok=1
curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4 -o "$tmp/v4" || ok=0
curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6 -o "$tmp/v6" || ok=0
if [ "$ok" = 1 ]; then
    grep -E '^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$' "$tmp/v4" > "$tmp/new" || true
    n4=$(wc -l < "$tmp/new")
    grep -E '^[0-9a-fA-F:]+/[0-9]{1,3}$' "$tmp/v6" >> "$tmp/new" || true
    n6=$(( $(wc -l < "$tmp/new") - n4 ))
    [ "$n4" -ge 5 ] && [ "$n6" -ge 3 ] || ok=0
fi
if [ "$ok" = 0 ]; then
    echo "reo-cf-ips: could not get a valid list from cloudflare.com; keeping the current one" >&2
    [ -s "$LIST" ] || exit 1
    cp "$LIST" "$tmp/new"
fi
sort -u "$tmp/new" -o "$tmp/new"
touch "$LIST"
old="$tmp/old"; sort -u "$LIST" > "$old"

# Caddy snippet (read by the caddy user)
{
    printf '# generated by reo-cf-ips from https://www.cloudflare.com/ips-v4 and ips-v6\n'
    printf 'trusted_proxies static'
    tr '\n' ' ' < "$tmp/new" | sed 's/ $//; s/^/ /'
    printf '\n'
} > "$tmp/snip"
install -o root -g caddy -m 0640 "$tmp/snip" "$SNIP" 2>/dev/null || install -m 0644 "$tmp/snip" "$SNIP"

if [ "$fw" = 1 ] && command -v ufw >/dev/null; then
    # add the new ranges first, then drop the ones that disappeared
    comm -13 "$old" "$tmp/new" | while read -r cidr; do
        ufw allow proto tcp from "$cidr" to any port 80,443 comment reo-cf >/dev/null
    done
    # first run: rules may exist from an earlier list file; make sure every current range is allowed
    if ! ufw status | grep -q reo-cf; then
        while read -r cidr; do ufw allow proto tcp from "$cidr" to any port 80,443 comment reo-cf >/dev/null; done < "$tmp/new"
    fi
    comm -23 "$old" "$tmp/new" | while read -r cidr; do
        ufw delete allow proto tcp from "$cidr" to any port 80,443 >/dev/null 2>&1 || true
    done
fi
install -o root -g reo -m 0640 "$tmp/new" "$LIST" 2>/dev/null || install -m 0644 "$tmp/new" "$LIST"

if [ "$reload" = 1 ] && systemctl is-active --quiet caddy; then
    systemctl reload caddy
fi
echo "reo-cf-ips: $(wc -l < "$LIST") Cloudflare ranges"
